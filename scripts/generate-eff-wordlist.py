#!/usr/bin/env python3
# Writes packages/tools/src/crypto/password-generator/words.ts from the EFF
# large wordlist for passphrases (7,776 words, CC BY 3.0 US).
#
# Download the list first and check its SHA-256:
#   curl -O https://www.eff.org/files/2016/07/18/eff_large_wordlist.txt
#   shasum -a 256 eff_large_wordlist.txt
#   addd35536511597a02fa0a9ff1e5284677b8883b83e986e43f15a3db996b903e
#
#   python3 scripts/generate-eff-wordlist.py eff_large_wordlist.txt packages/tools/src/crypto/password-generator/words.ts
import hashlib
import re
import sys

SHA256 = "addd35536511597a02fa0a9ff1e5284677b8883b83e986e43f15a3db996b903e"

source, target = sys.argv[1], sys.argv[2]
data = open(source, "rb").read()
if hashlib.sha256(data).hexdigest() != SHA256:
    sys.exit("The word list does not have the expected SHA-256.")
words = [line.split("\t")[1] for line in data.decode("ascii").splitlines() if line.strip()]
if len(words) != 7776 or len(set(words)) != 7776 or not all(re.fullmatch(r"[a-z-]+", w) for w in words):
    sys.exit("The word list is not 7,776 unique lowercase words.")
with open(target, "w") as out:
    out.write(
        "/*\n"
        " * Generated by scripts/generate-eff-wordlist.py. Do not edit by hand.\n"
        " *\n"
        " * The EFF large wordlist for passphrases: 7,776 words, so each word adds\n"
        " * log2(7776), about 12.9 bits. By the Electronic Frontier Foundation,\n"
        " * https://www.eff.org/dice, under the Creative Commons Attribution 3.0 US\n"
        " * license (CC BY 3.0 US).\n"
        " */\n"
        'export const EFF_WORDS: readonly string[] = "' + " ".join(words) + '".split(" ");\n'
    )
