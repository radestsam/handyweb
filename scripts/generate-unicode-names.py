#!/usr/bin/env python3
# Writes packages/tools/src/text/unicode-explorer/names.ts: the Unicode names of
# the blocks that the Unicode Character Inspector shows. The names come from
# the Unicode Character Database through the unicodedata module of Python, so
# the Unicode version is the one of the Python that runs the script.
#
#   python3 scripts/generate-unicode-names.py packages/tools/src/text/unicode-explorer/names.ts
import unicodedata, sys, json
BLOCKS = [
    (0x0000, 0x007F, "Basic Latin"),
    (0x0080, 0x00FF, "Latin-1 Supplement"),
    (0x0100, 0x017F, "Latin Extended-A"),
    (0x02B0, 0x02FF, "Spacing Modifier Letters"),
    (0x0300, 0x036F, "Combining Diacritical Marks"),
    (0x0600, 0x06FF, "Arabic"),
    (0x0750, 0x077F, "Arabic Supplement"),
    (0x0870, 0x089F, "Arabic Extended-B"),
    (0x08A0, 0x08FF, "Arabic Extended-A"),
    (0x2000, 0x206F, "General Punctuation"),
    (0x20A0, 0x20CF, "Currency Symbols"),
    (0x2100, 0x214F, "Letterlike Symbols"),
    (0x2190, 0x21FF, "Arrows"),
    (0x2600, 0x26FF, "Miscellaneous Symbols"),
    (0x2700, 0x27BF, "Dingbats"),
    (0xFB50, 0xFDFF, "Arabic Presentation Forms-A"),
    (0xFE00, 0xFE0F, "Variation Selectors"),
    (0xFE70, 0xFEFF, "Arabic Presentation Forms-B"),
    (0xFFF0, 0xFFFF, "Specials"),
    (0x1F300, 0x1F5FF, "Miscellaneous Symbols and Pictographs"),
    (0x1F600, 0x1F64F, "Emoticons"),
    (0x1F680, 0x1F6FF, "Transport and Map Symbols"),
    (0x1F900, 0x1F9FF, "Supplemental Symbols and Pictographs"),
    (0x1FA70, 0x1FAFF, "Symbols and Pictographs Extended-A"),
]
# Control characters have no name in UnicodeData; use the common aliases.
ALIASES = {0x09: "CHARACTER TABULATION", 0x0A: "LINE FEED", 0x0D: "CARRIAGE RETURN", 0x00: "NULL", 0x7F: "DELETE", 0x85: "NEXT LINE"}
out = []
for start, end, block in BLOCKS:
    names = []
    for cp in range(start, end + 1):
        n = unicodedata.name(chr(cp), "") or ALIASES.get(cp, "")
        names.append(n)
    out.append((start, block, names))
ts = []
ts.append("/*\n * Generated by scripts/generate-unicode-names.py from the Unicode Character\n * Database (Unicode %s). Do not edit by hand.\n *\n * Each entry is a block: its first code point, its name, and the names of its\n * code points joined by \"|\". An empty name is an unassigned code point.\n * Only the blocks that HandyWeb users need most are included, to keep the\n * download small.\n */\n" % unicodedata.unidata_version)
ts.append("export const UNICODE_VERSION = %s;\n\n" % json.dumps(unicodedata.unidata_version))
ts.append("export const NAME_BLOCKS: ReadonlyArray<readonly [start: number, block: string, names: string]> = [\n")
for start, block, names in out:
    ts.append("    [0x%04X, %s, %s],\n" % (start, json.dumps(block), json.dumps("|".join(names))))
ts.append("];\n")
open(sys.argv[1], "w").write("".join(ts))
